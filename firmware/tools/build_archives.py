"""Generate deterministic, original monochrome demo pages for offline navigation."""
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]


def build():
    output = ROOT / 'runtime/firmware-pages'
    output.mkdir(parents=True, exist_ok=True)
    arrays = []
    for page, title in [(3, 'HORIZON'), (4, 'CONTOURS'), (5, 'NIGHT SKY')]:
        image = Image.new('1', (800, 480), 1)
        draw = ImageDraw.Draw(image)
        draw.rectangle((24, 24, 775, 455), outline=0, width=3)
        draw.text((44, 45), f'INKDESK / {title}', fill=0)
        draw.text((44, 420), f'{page} / 5    OFFLINE DEMO', fill=0)
        for index in range(8):
            if page == 3:
                y = 155 + index * 27
                draw.line([(45, y), (260, y - 60), (538, y + 30), (754, y)], fill=0, width=4)
            elif page == 4:
                x = 120 + index * 28
                draw.ellipse((x, 108 + index * 12, 800 - x, 384 - index * 12), outline=0, width=3)
            else:
                x = 100 + index * 83
                y = 134 + (index * 71) % 218
                draw.line((x - 9, y, x + 9, y), fill=0, width=3)
                draw.line((x, y - 9, x, y + 9), fill=0, width=3)
        image.save(output / f'page-{page}.png')
        pixels = image.tobytes()
        rows = [','.join(map(str, pixels[i:i+100])) for i in range(0, len(pixels), 100)]
        arrays.append(f'static const uint8_t ARCHIVE_{page}[48000] = {{\n' +
                      ',\n'.join(rows) + '\n};\n')
    (ROOT / 'firmware/include/archived_pages.h').write_text(
        '// Generated by firmware/tools/build_archives.py; do not edit.\n#pragma once\n#include <stdint.h>\n'
        + ''.join(arrays)
        + 'static const uint8_t* const ARCHIVED_PAGES[] = {ARCHIVE_3, ARCHIVE_4, ARCHIVE_5};\n')


if __name__ == '__main__':
    build()
