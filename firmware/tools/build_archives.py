"""Bundle offline manual pages without changing originals or cloud archives."""
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo
import hashlib
import json

from PIL import Image, ImageDraw, ImageOps

ROOT = Path(__file__).resolve().parents[2]


def build():
    output = ROOT / 'runtime/firmware-pages'
    output.mkdir(parents=True, exist_ok=True)
    sources = ['assets/ducati-original.jpg', 'assets/lanting-calligraphy-dark.png', 'runtime/cat-weather.png']
    records = []
    arrays = []
    for index, name in enumerate(sources, 2):
        path = ROOT / name
        with Image.open(path) as original:
            image = ImageOps.exif_transpose(original).convert('L')
            if index == 2:
                # Preserve the complete photograph; white margins avoid cropping.
                image = ImageOps.pad(image, (800, 480), color=255).convert('1')
            else:
                image = image.resize((800, 480), Image.Resampling.LANCZOS)
                image = image.point(lambda p: 255 if p >= 150 else 0).convert('1')
        if index == 4:
            # This page is intentionally frozen; don't imply its weather is live.
            stamp = datetime.fromtimestamp(path.stat().st_mtime, ZoneInfo('Asia/Shanghai'))
            draw = ImageDraw.Draw(image)
            draw.rectangle((0, 464, 799, 479), fill=1)
            draw.text((20, 466), 'ARCHIVE / '+stamp.strftime('%Y-%m-%d %H:%M')+' / NOT LIVE', fill=0)
        image.save(output / f'page-{index}.png')
        data = image.tobytes()
        assert len(data) == 48000
        arrays.append('static const uint8_t ARCHIVE_%d[48000] = {\n'%index +
                      ',\n'.join(','.join(str(b) for b in data[i:i+100]) for i in range(0,len(data),100))+'\n};\n')
        records.append({'page': index, 'source': name, 'source_sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
                        'bitmap_sha256': hashlib.sha256(data).hexdigest()})
    (ROOT / 'firmware/include/archived_pages.h').write_text(
        '// Generated by firmware/tools/build_archives.py; do not edit.\n#pragma once\n#include <stdint.h>\n'+
        ''.join(arrays)+'static const uint8_t* const ARCHIVED_PAGES[] = {ARCHIVE_2,ARCHIVE_3,ARCHIVE_4};\n')
    (output / 'manifest.json').write_text(json.dumps(records, indent=2)+'\n')
    print('Built three offline manual pages; originals unchanged.')


if __name__ == '__main__':
    build()
